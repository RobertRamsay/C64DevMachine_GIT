function grid(text) {
  return text.split('\n').map(s => s.trimEnd()).filter(s => s.length > 0);
}
function pad21(rows, top = 0) {
  const out = Array(21).fill('............');
  rows.forEach((r, i) => { out[top + i] = r.padEnd(12, '.'); });
  return out;
}
function mirror(rows) { return rows.map(r => r.split('').reverse().join('')); }

function compose(upper, lower) { return pad21([...grid(upper), ...grid(lower)]); }

export const FRAMES = [];       // [name, rows21]
const add = (name, rows) => {
  if (rows.length !== 21) throw new Error(name + ' has ' + rows.length + ' rows');
  rows.forEach(r => { if (r.length !== 12) throw new Error(name + ' row width ' + r.length + ': ' + r); });
  FRAMES.push([name, rows]);
};

// order matters: the game uses FRAME index arithmetic
// 0-4   side right: stand, run 1-4
// 5-9   side left
// 10-14 down (towards camera)
// 15-19 up (away)
add('R_STAND', pad21(grid(STAND_R)));
RUN_R.forEach((l, i) => add('R_RUN' + i, compose(UP_R, l)));
add('L_STAND', mirror(pad21(grid(STAND_R))));
RUN_R.forEach((l, i) => add('L_RUN' + i, mirror(compose(UP_R, l))));
add('D_STAND', pad21(grid(STAND_D)));
RUN_D.forEach((l, i) => add('D_RUN' + i, compose(UP_D, l)));
add('U_STAND', pad21(grid(STAND_U)));
RUN_D.forEach((l, i) => add('U_RUN' + i, compose(UP_U, l)));
// 20-21 kick R/L, 22-23 slide R/L, 24-25 fallen R/L, 26 celebrate,
// 27 dive up, 28 dive down, 29 keeper holding
add('R_KICK', pad21(grid(KICK_R)));
add('L_KICK', mirror(pad21(grid(KICK_R))));
add('R_SLIDE', pad21(grid(SLIDE_R)));
add('L_SLIDE', mirror(pad21(grid(SLIDE_R))));
