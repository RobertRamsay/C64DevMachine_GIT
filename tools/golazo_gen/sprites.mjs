add('BLANK', Array(21).fill('.'.repeat(12)));

export const IDX = Object.fromEntries(FRAMES.map(([n], i) => [n, i]));

const BITS = { '.': 0, S: 1, C: 2, B: 3 };
export function encode(rows) {
  const out = [];
  for (const r of rows) {
    let v = 0;
    for (const ch of r) v = (v << 2) | BITS[ch];
    out.push((v >> 16) & 255, (v >> 8) & 255, v & 255);
  }
  out.push(0);
  return out;
}
export function spriteBytes() { return FRAMES.flatMap(([, rows]) => encode(rows)); }
