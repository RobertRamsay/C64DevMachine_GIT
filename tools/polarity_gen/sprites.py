def mirror_mc(rows):
    return [r[::-1] for r in rows]

def mirror_hr(rows):
    return [r.ljust(24, '.')[::-1] for r in rows]

def enc_mc(rows):
    rows = [r.ljust(12, '.') for r in rows] + ["." * 12] * (21 - len(rows))
    out = []
    for r in rows[:21]:
        bits = 0
        for ch in r:
            bits = (bits << 2) | {'.': 0, '1': 1, '2': 2, '3': 3}[ch]
        out += [(bits >> 16) & 255, (bits >> 8) & 255, bits & 255]
    return out + [0]

def enc_hr(rows):
    rows = [r.ljust(24, '.') for r in rows] + ["." * 24] * (21 - len(rows))
    out = []
    for r in rows[:21]:
        bits = int(r.replace('#', '1').replace('.', '0'), 2)
        out += [(bits >> 16) & 255, (bits >> 8) & 255, bits & 255]
    return out + [0]

