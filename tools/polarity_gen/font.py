def glyph_bytes(code):
    rows = G.get(code)
    if rows is None:
        return [0] * 8
    return [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows]

def screen_code(ch):
    """ASCII -> screen code for this font."""
    o = ord(ch)
    if 'A' <= ch <= 'Z': return o - 64
    if 'a' <= ch <= 'z': return o - 96
    if ch == '@': return 0
    if 32 <= o <= 63: return o
    return 32

def text_codes(s):
    return [screen_code(c) for c in s]


